  for (const p of products) {
    const categoryId = catMap[p.category];

    // Check if item already exists by name in this restaurant
    const existing = await prisma.product.findFirst({
      where: {
        restaurantId,
        OR: [
          { name: p.name },
          { nameAm: p.nameAm },
        ],
      },
    });

    if (existing) {
      await prisma.product.update({
        where: { id: existing.id },
        data: {
          name: p.name,
          nameAm: p.nameAm,
          price: p.price,
          categoryId,
          description: p.description,
          descriptionAm: p.descriptionAm,
          imageUrl: p.imageUrl,
          isAvailable: true,
          isActive: true,
        },
      });
      updatedCount++;
    } else {
      await prisma.product.create({
        data: {
          restaurantId,
          categoryId,
          name: p.name,
          nameAm: p.nameAm,
          price: p.price,
          description: p.description,
          descriptionAm: p.descriptionAm,
          imageUrl: p.imageUrl,
          isAvailable: true,
          isActive: true,
        },
      });
      addedCount++;
    }
  }

